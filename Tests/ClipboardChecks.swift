import AppKit

@MainActor
func checkClipboard() throws {
    let root = FileManager.default.temporaryDirectory.appendingPathComponent("clipboard-check-" + UUID().uuidString)
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("checks-" + UUID().uuidString))
    let url = root.appendingPathComponent("clipboard.json")
    var clock = Date()
    let store = ClipboardStore(url: url, pasteboard: pasteboard, now: { clock })
    defer {
        store.stop()
        pasteboard.releaseGlobally()
        try? FileManager.default.removeItem(at: root)
    }
    func text(_ value: String) {
        pasteboard.clearContents()
        pasteboard.setString(value, forType: .string)
        store.poll()
    }
    text("before-enable")
    check(store.entries.isEmpty, "Recording must be opt-in")
    try store.setEnabled(true)
    store.stop()
    store.poll()
    check(store.entries.isEmpty, "Enabling must not import the pre-existing clipboard")
    text("Hello 世界")
    checkEqual(store.entries.first?.kind, .text)
    checkEqual(store.search("hello").count, 1)
    let link = ClipboardEntry(id: UUID(), kind: .text, text: "https://example.com/path", paths: [], date: clock)
    checkEqual(link.linkURL?.host, "example.com")
    let plain = ClipboardEntry(id: UUID(), kind: .text, text: "See https://example.com", paths: [], date: clock)
    checkNil(plain.linkURL)
    var oldEntry = try JSONSerialization.jsonObject(with: JSONEncoder().encode(link)) as! [String: Any]
    oldEntry.removeValue(forKey: "sourceAppName")
    oldEntry.removeValue(forKey: "sourceBundleIdentifier")
    let decoded = try JSONDecoder().decode(ClipboardEntry.self, from: JSONSerialization.data(withJSONObject: oldEntry))
    checkNil(decoded.sourceBundleIdentifier)
    text("Second")
    text("Hello 世界")
    checkEqual(store.entries.count, 2)
    let id = try unwrap(store.entries.first?.id)
    try store.copy(id)
    checkEqual(pasteboard.string(forType: .string), "Hello 世界")
    store.poll()
    checkEqual(store.entries.count, 2)
    for marker in ClipboardStore.sensitiveTypes {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("secret", forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
        pasteboard.writeObjects([item])
        store.poll()
        checkEqual(store.entries.count, 2)
    }
    text(String(repeating: "x", count: ClipboardStore.maximumTextBytes + 1))
    checkEqual(store.entries.count, 2)
    try store.setEnabled(false)
    text("paused")
    checkEqual(store.entries.count, 2)
    try store.setEnabled(true)
    store.stop()
    store.poll()
    checkEqual(store.entries.count, 2)

    store.setSuspended(true)
    text("sleeping")
    checkEqual(store.entries.count, 2)
    store.setSuspended(false); store.stop(); store.poll()
    checkEqual(store.entries.count, 2)

    let file = root.appendingPathComponent("original.txt")
    try Data("Original file".utf8).write(to: file)
    pasteboard.clearContents()
    pasteboard.writeObjects([file as NSURL])
    store.poll()
    let files = try unwrap(store.entries.first)
    checkEqual(files.kind, .files)
    checkEqual(files.paths, [file.path])
    try store.copy(files.id)
    let copied = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
    checkEqual(copied?.first?.path, file.path)
    try FileManager.default.removeItem(at: file)
    pasteboard.clearContents(); pasteboard.setString("preserved", forType: .string)
    do { try store.copy(files.id); fail("Missing file must not copy") } catch {}
    checkEqual(pasteboard.string(forType: .string), "preserved")
    let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 32, pixelsHigh: 24,
        bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
        colorSpaceName: .deviceRGB, bytesPerRow: 128, bitsPerPixel: 32)!
    for x in 0..<32 { for y in 0..<24 {
        bitmap.setColor(NSColor(deviceRed: 0.2, green: 0.5, blue: 0.8, alpha: 1), atX: x, y: y)
    } }
    let png = try unwrap(bitmap.representation(using: .png, properties: [:]))
    pasteboard.clearContents(); pasteboard.setData(png, forType: .png); store.poll()
    let image = try unwrap(store.entries.first)
    checkEqual(image.kind, .image)
    let cachedURL = try unwrap(store.imageURL(for: image))
    check(FileManager.default.fileExists(atPath: cachedURL.path))
    checkNotNil(store.thumbnail(for: image))
    try store.copy(image.id)
    checkEqual(pasteboard.data(forType: .png), png)
    let before = store.entries.count
    pasteboard.clearContents(); pasteboard.setData(png, forType: .png); store.poll()
    checkEqual(store.entries.count, before)
    pasteboard.clearContents(); pasteboard.setData(Data("invalid".utf8), forType: .png); store.poll()
    checkEqual(store.entries.count, before)
    checkNotNil(store.notice)
    checkEqual(store.search("", kind: .image).count, 1)
    checkEqual(store.search("original", kind: .files).count, 1)
    try store.setRetentionDays(30)
    let restored = ClipboardStore(url: url, pasteboard: pasteboard, now: { clock })
    checkEqual(restored.retentionDays, 30)
    checkEqual(restored.entries, store.entries)
    check(restored.enabled)
    let attrs = try FileManager.default.attributesOfItem(atPath: url.path)
    checkEqual((attrs[.posixPermissions] as? NSNumber)?.intValue, 0o600)
    try store.setPinned(true, for: image.id)
    clock = clock.addingTimeInterval(8 * 86400)
    store.poll()
    check(!store.entries.isEmpty)
    try store.setRetentionDays(7)
    checkEqual(store.entries.count, 1)
    check(store.entries[0].isPinned)
    check(FileManager.default.fileExists(atPath: cachedURL.path))
    try store.setPinned(false, for: image.id)
    check(store.entries.isEmpty)
    check(!FileManager.default.fileExists(atPath: cachedURL.path), "Expired image bytes must be removed")
    try store.setRetentionDays(30)
    text("expires-in-30-days")
    clock = clock.addingTimeInterval(31 * 86400)
    store.poll()
    check(store.entries.isEmpty)
    text("keep me")
    let pinnedID = store.entries[0].id
    try store.setPinned(true, for: pinnedID)
    text("keep me")
    checkEqual(store.entries[0].id, pinnedID)
    check(store.entries[0].isPinned)
    let pinnedRestore = ClipboardStore(url: url, pasteboard: pasteboard, now: { clock })
    check(pinnedRestore.entries[0].isPinned)
    for index in 0..<1005 { text("Entry \(index)") }
    check(store.entries.contains { $0.id == pinnedID && $0.isPinned })
    for entry in store.entries.filter({ !$0.isPinned }).prefix(199) { try store.setPinned(true, for: entry.id) }
    let extra = store.entries.first { !$0.isPinned }!
    do { try store.setPinned(true, for: extra.id); fail("Pin cap must be enforced") } catch {}
    checkEqual(store.entries.filter(\.isPinned).count, 200)
    checkEqual(store.entries.count, 1000)
    checkEqual(store.entries.first?.text, "Entry 1004")
    try store.remove(store.entries[0].id)
    checkEqual(store.entries.count, 999)
    try store.clear()
    store.stop()
    check(store.entries.isEmpty)
    checkEqual(pasteboard.string(forType: .string), "Entry 1004")

    // Cache budget: sparse files avoid allocating hundreds of megabytes for the test.
    try FileManager.default.createDirectory(at: store.imageDirectory, withIntermediateDirectories: true)
    var images: [ClipboardEntry] = []
    for index in 0..<130 {
        let name = String(format: "%064x", index) + ".png"
        let imageURL = store.imageDirectory.appendingPathComponent(name)
        FileManager.default.createFile(atPath: imageURL.path, contents: nil)
        let handle = try FileHandle(forWritingTo: imageURL)
        try handle.truncate(atOffset: UInt64(ClipboardStore.maximumImageBytes))
        try handle.close()
        images.append(ClipboardEntry(id: UUID(), kind: .image, text: "", paths: [], imageFile: name,
                                    imageType: NSPasteboard.PasteboardType.png.rawValue, date: clock))
    }
    let encoded = try JSONEncoder().encode(images)
    let array = try JSONSerialization.jsonObject(with: encoded)
    try JSONSerialization.data(withJSONObject: ["version": 1, "enabled": false, "retentionDays": 7, "entries": array]).write(to: url)
    let bounded = ClipboardStore(url: url, pasteboard: pasteboard, now: { clock })
    checkNil(bounded.error)
    checkEqual(bounded.entries.count, 128)
    checkEqual(try FileManager.default.contentsOfDirectory(atPath: store.imageDirectory.path).count, 128)
    try bounded.clear(); bounded.stop()
    checkEqual(try FileManager.default.contentsOfDirectory(atPath: store.imageDirectory.path).count, 0)
    try Data("broken-json".utf8).write(to: url)
    let corrupt = ClipboardStore(url: url, pasteboard: pasteboard)
    checkNotNil(corrupt.error)
    check(!corrupt.enabled)
    do { try corrupt.setEnabled(true); fail("Corrupt storage must not be overwritten on enable") } catch {}
    checkEqual(try String(contentsOf: url), "broken-json")
    try corrupt.clear(); corrupt.stop()
    checkNil(corrupt.error)
    checkEqual(ClipboardSearchHighlight.ranges(in: "可重新选择连接方式", query: "fangshi"), [NSRange(location: 7, length: 2)])
    checkEqual(ClipboardSearchHighlight.ranges(in: "😀设计说明", query: "sjsm"), [NSRange(location: 2, length: 4)])
    checkEqual(ClipboardSearchHighlight.ranges(in: "设计说明", query: "说明"), [NSRange(location: 2, length: 2)])
    checkEqual(ClipboardSearchHighlight.ranges(in: "ABC abc", query: "abc").count, 2)
    check(ClipboardSearchHighlight.ranges(in: "设计", query: "zzqq").isEmpty, "No false highlight")
    let pinyin = ClipboardStore(url: root.appendingPathComponent("pinyin.json"), pasteboard: pasteboard)
    defer { pinyin.stop() }
    try pinyin.setEnabled(true); pinyin.stop()
    pasteboard.clearContents(); pasteboard.setString("项目设计说明 Release", forType: .string); pinyin.poll()
    for query in ["shejishuoming", "sj sm", "SJS M", "设计", "sheji release", "jishuo", "shèjì", "   "] {
        checkEqual(pinyin.search(query).count, 1)
    }
    checkEqual(pinyin.search("zzqqxx").count, 0)
    checkEqual(pinyin.search("sj", kind: .image).count, 0)
    let chineseFile = root.appendingPathComponent("项目计划.txt")
    try Data().write(to: chineseFile)
    pasteboard.clearContents(); pasteboard.writeObjects([chineseFile as NSURL]); pinyin.poll()
    checkEqual(pinyin.search("xiangmujihua", kind: .files).count, 1)
    checkEqual(pinyin.search("xmjh", kind: .files).count, 1)
    try pinyin.clear()
    checkEqual(pinyin.search("sj").count, 0)
    pasteboard.clearContents(); pasteboard.setString("original command", forType: .string); pinyin.poll()
    let organized = pinyin.entries[0].id
    try pinyin.setOrganization(organized, alias: "发布命令", group: "工作")
    check(pinyin.entries[0].isPinned, "Grouped entries are pinned")
    checkEqual(pinyin.search("fbml").first?.id, organized)
    let organizationReload = ClipboardStore(url: root.appendingPathComponent("pinyin.json"), pasteboard: pasteboard)
    checkEqual(organizationReload.entries[0].alias, "发布命令")
    checkEqual(organizationReload.entries[0].group, "工作")
    try pinyin.copy(organized)
    checkEqual(pasteboard.string(forType: .string), "original command")
    pasteboard.clearContents(); pasteboard.setString("original command", forType: .string); pinyin.poll()
    checkEqual(pinyin.entries[0].alias, "发布命令")
    try pinyin.remove(organized)
    check(pinyin.canUndoDelete, "Deletion can be undone")
    checkEqual(try pinyin.undoDelete(), organized)
    checkEqual(pinyin.entries[0].group, "工作")
    check(!pinyin.canUndoDelete, "Undo is consumed")
    pasteboard.clearContents(); pasteboard.setData(png, forType: .png); pinyin.poll()
    let imageEntry = pinyin.entries[0]
    let retainedImage = pinyin.imageURL(for: imageEntry)!
    try pinyin.remove(imageEntry.id)
    check(FileManager.default.fileExists(atPath: retainedImage.path), "Undo retains image on disk")
    checkEqual(try pinyin.undoDelete(), imageEntry.id)
    try pinyin.copy(imageEntry.id)
    checkEqual(pasteboard.data(forType: .png), png)
    try pinyin.remove(imageEntry.id)
    try pinyin.clear()
    check(!pinyin.canUndoDelete, "Clear must not be undone")
    check(!FileManager.default.fileExists(atPath: retainedImage.path), "Clear removes undo image")
    organizationReload.stop()
    print("PASS: aliases/groups persistence, duplicate retention, original copy and text/image undo")
    print("PASS: pinyin full, initials, partial, accents, mixed tokens, filenames and cleared cache")
    print("PASS: clipboard opt-in, sensitive markers, text dedup/search, file references, image round-trip, retention, cache budget, permissions and corrupt-storage protection")
}
