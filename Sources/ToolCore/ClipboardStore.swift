import AppKit
import CryptoKit
import ImageIO

struct ClipboardEntry: Codable, Equatable, Identifiable {
    enum Kind: String, Codable { case text, image, files }
    var id: UUID
    var kind: Kind
    var text: String
    var paths: [String]
    var imageFile: String?
    var imageType: String?
    var date: Date
    var alias: String? = nil
    var group: String? = nil
    var pinned: Bool? = nil
    var isPinned: Bool { pinned == true }
    var sourceAppName: String? = nil
    var sourceBundleIdentifier: String? = nil
    var linkURL: URL? {
        guard kind == .text, let url = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines)),
              ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).contains(where: { $0.isWhitespace }) else { return nil }
        return url
    }
    var typeTitle: String { linkURL != nil ? "链接" : kind == .text ? "文字" : kind == .image ? "图片" : "文件" }
    var relativeTime: String {
        let seconds = max(0, Int(Date().timeIntervalSince(date)))
        if seconds < 60 { return "刚刚" }
        if seconds < 3600 { return "\(seconds / 60) 分钟前" }
        if seconds < 86400 { return "\(seconds / 3600) 小时前" }
        return "\(seconds / 86400) 天前"
    }
    var title: String {
        switch kind {
        case .text: return text
        case .image: return "图片"
        case .files: return paths.map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: "、")
        }
    }
}

@MainActor
final class ClipboardStore {
    static let maximumEntries = 100
    static let maximumPins = 20
    static let maximumTextBytes = 64 * 1024
    static let maximumImageBytes = 20 * 1024 * 1024
    static let maximumCacheBytes = 256 * 1024 * 1024
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"
    ]
    private struct Document: Codable {
        var version = 1
        var enabled: Bool
        var retentionDays: Int
        var entries: [ClipboardEntry]
    }
    private struct SearchIndex {
        let source: String
        let full: String
        let initials: String
    }
    private var deletedEntry: ClipboardEntry?
    var canUndoDelete: Bool { deletedEntry != nil }
    var groups: [String] { Array(Set(entries.compactMap(\.group))).sorted() }
    private var searchIndices: [UUID: SearchIndex] = [:]
    private let url: URL
    private let pasteboard: NSPasteboard
    private let now: () -> Date
    private var timer: Timer?
    private var suspended = false
    private var lastChange: Int
    private var lastPrune = Date.distantPast
    private(set) var entries: [ClipboardEntry] = []
    private(set) var enabled = false
    private(set) var retentionDays = 7
    private(set) var error: String?
    private(set) var notice: String?
    var onChange: (() -> Void)?
    var imageDirectory: URL { url.deletingLastPathComponent().appendingPathComponent("clipboard-images", isDirectory: true) }
    nonisolated static var applicationURL: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("local.tango.macbglive/clipboard.json")
    }
    init(url: URL = ClipboardStore.applicationURL, pasteboard: NSPasteboard = .general,
         now: @escaping () -> Date = Date.init) {
        self.url = url
        self.pasteboard = pasteboard
        self.now = now
        lastChange = pasteboard.changeCount
        guard FileManager.default.fileExists(atPath: url.path) else { return }
        do {
            let attributes = try FileManager.default.attributesOfItem(atPath: url.path)
            guard ((attributes[.size] as? NSNumber)?.intValue ?? 0) <= 16 * 1024 * 1024 else {
                throw failure("历史文件过大，已暂停读取。")
            }
            let document = try JSONDecoder().decode(Document.self, from: Data(contentsOf: url))
            guard document.version == 1 else { throw failure("历史文件版本不兼容。") }
            enabled = document.enabled
            retentionDays = document.retentionDays == 30 ? 30 : 7
            entries = document.entries
            prune()
            try persist()
            try removeUnusedImages()
        } catch {
            enabled = false
            entries = []
            self.error = "无法读取剪贴板历史，原文件已保留。\(error.localizedDescription)"
        }
    }
    deinit { timer?.invalidate() }

    func start() {
        stop()
        lastChange = pasteboard.changeCount
        guard error == nil, !suspended else { return }
        // A cheap changeCount check; never re-read unchanged clipboard contents.
        let timer = Timer(timeInterval: enabled ? 1 : 60, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.poll() }
        }
        timer.tolerance = enabled ? 0.3 : 5
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }
    func stop() { timer?.invalidate(); timer = nil }
    func setSuspended(_ value: Bool) {
        guard suspended != value else { return }
        suspended = value
        if value { stop() } else { start() }
    }

    func setEnabled(_ value: Bool) throws {
        guard error == nil else { throw failure(error!) }
        let old = enabled
        enabled = value
        do { try persist() } catch { enabled = old; throw error }
        start()
        onChange?()
    }
    func setRetentionDays(_ days: Int) throws {
        guard error == nil, [7, 30].contains(days) else { throw failure(error ?? "保留时间请选择 7 天或 30 天。") }
        let old = entries
        let previous = retentionDays
        retentionDays = days
        prune()
        do { try persist() } catch { retentionDays = previous; entries = old; throw error }
        try removeUnusedImages()
        onChange?()
    }
    func poll() {
        guard error == nil, !suspended else { return }
        if now().timeIntervalSince(lastPrune) >= 60 {
            lastPrune = now()
            let old = entries
            prune()
            if old != entries { saveOrPause(); onChange?() }
        }
        guard enabled, error == nil, pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        notice = nil
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard Self.sensitiveTypes.isDisjoint(with: types) else { return }
        // Finder image files remain file references rather than duplicated image data.
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            let urls = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
            let paths = urls.filter(\.isFileURL).map(\.path)
            guard !paths.isEmpty, paths.count <= 1000, paths.joined().utf8.count <= Self.maximumTextBytes else { return }
            append(ClipboardEntry(id: UUID(), kind: .files, text: "", paths: paths, date: now()))
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            let type: NSPasteboard.PasteboardType = types.contains(NSPasteboard.PasteboardType.png.rawValue) ? .png : .tiff
            guard let data = pasteboard.data(forType: type), !data.isEmpty, data.count <= Self.maximumImageBytes,
                  let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
                  let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? Double,
                  let height = properties[kCGImagePropertyPixelHeight] as? Double,
                  width > 0, height > 0, width * height <= 40_000_000 else {
                notice = "已跳过过大或无效的图片（上限 20 MB / 4000 万像素）。"
                onChange?(); return
            }
            let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            let filename = hash + (type == .png ? ".png" : ".tiff")
            do {
                try FileManager.default.createDirectory(at: imageDirectory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
                let imageURL = imageDirectory.appendingPathComponent(filename)
                if !FileManager.default.fileExists(atPath: imageURL.path) {
                    try data.write(to: imageURL, options: .atomic)
                    try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: imageURL.path)
                }
                append(ClipboardEntry(id: UUID(), kind: .image, text: "", paths: [], imageFile: filename,
                                      imageType: type.rawValue, date: now()))
            } catch { pauseAfterFailure(error) }
        } else if let text = pasteboard.string(forType: .string) {
            guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  text.utf8.count <= Self.maximumTextBytes else { return }
            append(ClipboardEntry(id: UUID(), kind: .text, text: text, paths: [], date: now()))
        }
    }
    private func append(_ value: ClipboardEntry) {
        var entry = value
        let source = NSWorkspace.shared.frontmostApplication
        let declaredSource = pasteboard.string(forType: NSPasteboard.PasteboardType("org.nspasteboard.source"))
        let bundleID = declaredSource?.isEmpty == false ? declaredSource : source?.bundleIdentifier
        entry.sourceBundleIdentifier = bundleID
        entry.sourceAppName = bundleID.flatMap { NSRunningApplication.runningApplications(withBundleIdentifier: $0).first?.localizedName }
            ?? (bundleID == source?.bundleIdentifier ? source?.localizedName : nil)
        if let existing = entries.first(where: { $0.kind == entry.kind && $0.text == entry.text && $0.paths == entry.paths && $0.imageFile == entry.imageFile }) {
            entry.id = existing.id
            entry.pinned = existing.pinned
            entry.alias = existing.alias
            entry.group = existing.group
        }
        entries.removeAll { $0.kind == entry.kind && $0.text == entry.text && $0.paths == entry.paths && $0.imageFile == entry.imageFile }
        entries.insert(entry, at: 0)
        prune()
        saveOrPause()
        onChange?()
    }
    func search(_ query: String, kind: ClipboardEntry.Kind? = nil) -> [ClipboardEntry] {
        let liveIDs = Set(entries.map(\.id))
        searchIndices = searchIndices.filter { liveIDs.contains($0.key) }
        let query = query.trimmingCharacters(in: .whitespacesAndNewlines)
        let tokens = query.split(whereSeparator: { $0.isWhitespace }).map(String.init)
        return entries.filter { entry in
            guard kind == nil || entry.kind == kind else { return false }
            if query.isEmpty { return true }
            let source = entry.title + "\n" + entry.paths.joined(separator: "\n") + "\n" + (entry.alias ?? "") + "\n" + (entry.group ?? "")
            if source.localizedCaseInsensitiveContains(query) { return true }
            return tokens.allSatisfy { token in
                if source.localizedCaseInsensitiveContains(token) { return true }
                let folded = token.folding(options: [.diacriticInsensitive, .caseInsensitive, .widthInsensitive], locale: Locale(identifier: "en_US_POSIX"))
                guard !folded.isEmpty, folded.allSatisfy({ $0.isASCII && ($0.isLetter || $0.isNumber) }) else { return false }
                let index: SearchIndex
                if let cached = searchIndices[entry.id], cached.source == source {
                    index = cached
                } else {
                    guard source.unicodeScalars.contains(where: {
                        (0x3400...0x9FFF).contains($0.value) || (0x20000...0x323AF).contains($0.value)
                    }) else { return false }
                    let latin = (source.applyingTransform(.mandarinToLatin, reverse: false) ?? source)
                        .folding(options: [.diacriticInsensitive, .caseInsensitive, .widthInsensitive], locale: Locale(identifier: "en_US_POSIX"))
                    let syllables = latin.split(whereSeparator: { !$0.isLetter && !$0.isNumber })
                    index = SearchIndex(source: source, full: syllables.joined(),
                        initials: String(syllables.compactMap(\.first)))
                    searchIndices[entry.id] = index
                }
                return index.full.contains(folded) || index.initials.contains(folded)
            }
        }
    }
    func imageURL(for entry: ClipboardEntry) -> URL? {
        guard let name = entry.imageFile, name.range(of: "^[a-f0-9]{64}\\.(png|tiff)$", options: .regularExpression) != nil else { return nil }
        return imageDirectory.appendingPathComponent(name)
    }
    func detail(for entry: ClipboardEntry) -> String {
        switch entry.kind {
        case .text: return entry.linkURL?.host ?? "\(entry.text.count) 个字符"
        case .files: return entry.paths.count == 1 ? entry.paths[0] : "\(entry.paths.count) 个文件"
        case .image:
            guard let url = imageURL(for: entry), let source = CGImageSourceCreateWithURL(url as CFURL, nil),
                  let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                  let width = props[kCGImagePropertyPixelWidth] as? Int, let height = props[kCGImagePropertyPixelHeight] as? Int else { return "图片" }
            return "\(width) × \(height)"
        }
    }

    func thumbnail(for entry: ClipboardEntry) -> NSImage? {
        guard let url = imageURL(for: entry), let source = CGImageSourceCreateWithURL(url as CFURL, nil),
              let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 256,
                kCGImageSourceCreateThumbnailWithTransform: true
              ] as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
    }
    func copy(_ id: UUID) throws {
        guard let entry = entries.first(where: { $0.id == id }) else { throw failure("记录已删除。") }
        let success: Bool
        switch entry.kind {
        case .text:
            pasteboard.clearContents()
            success = pasteboard.setString(entry.text, forType: .string)
        case .files:
            guard !entry.paths.isEmpty, entry.paths.allSatisfy({ FileManager.default.fileExists(atPath: $0) }) else {
                throw failure("原文件已移动或删除，无法复制。历史仅保存文件引用。")
            }
            pasteboard.clearContents()
            success = pasteboard.writeObjects(entry.paths.map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            guard let url = imageURL(for: entry), let type = entry.imageType, [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue].contains(type) else { throw failure("图片记录无效。") }
            let data = try Data(contentsOf: url)
            guard data.count <= Self.maximumImageBytes else { throw failure("缓存图片过大。") }
            pasteboard.clearContents()
            success = pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
        }
        lastChange = pasteboard.changeCount
        if !success { throw failure("无法写入系统剪贴板，请重试。") }
    }
    func setPinned(_ pinned: Bool, for id: UUID) throws {
        guard error == nil else { throw failure(error!) }
        guard let index = entries.firstIndex(where: { $0.id == id }) else { throw failure("记录已删除。") }
        guard !pinned || entries[index].isPinned || entries.filter(\.isPinned).count < Self.maximumPins else {
            throw failure("最多固定 20 条，请先取消固定其他内容。")
        }
        let old = entries
        entries[index].pinned = pinned
        prune()
        do { try persist() } catch { entries = old; throw error }
        try removeUnusedImages()
        onChange?()
    }

    func setOrganization(_ id: UUID, alias: String, group: String) throws {
        guard error == nil, let index = entries.firstIndex(where: { $0.id == id }) else { throw failure(error ?? "记录已删除") }
        let alias = alias.trimmingCharacters(in: .whitespacesAndNewlines)
        let group = group.trimmingCharacters(in: .whitespacesAndNewlines)
        guard alias.count <= 80, group.count <= 30 else { throw failure("别名最多 80 字，分组最多 30 字。") }
        guard group.isEmpty || entries[index].isPinned || entries.filter(\.isPinned).count < Self.maximumPins else { throw failure("分组会固定此项，最多固定 20 条。") }
        let old = entries
        entries[index].alias = alias.isEmpty ? nil : alias
        entries[index].group = group.isEmpty ? nil : group
        if !group.isEmpty { entries[index].pinned = true }
        do { try persist() } catch { entries = old; throw error }
        onChange?()
    }
    func remove(_ id: UUID) throws {
        guard error == nil else { throw failure(error!) }
        guard let entry = entries.first(where: { $0.id == id }) else { return }
        let old = entries
        entries.removeAll { $0.id == id }
        do { try persist() } catch { entries = old; throw error }
        deletedEntry = entry
        try removeUnusedImages()
        onChange?()
    }
    @discardableResult func undoDelete() throws -> UUID? {
        guard error == nil else { throw failure(error!) }
        guard let entry = deletedEntry else { return nil }
        // Do not evict another record or undo a newer copy of the same content.
        guard !entries.contains(where: { $0.id == entry.id || ($0.kind == entry.kind && $0.text == entry.text && $0.paths == entry.paths && $0.imageFile == entry.imageFile) }) else {
            throw failure("相同内容已重新复制，无需恢复旧记录。")
        }
        guard entries.count < Self.maximumEntries,
              !entry.isPinned || entries.filter(\.isPinned).count < Self.maximumPins else { throw failure("容量已满，请先删除或取消固定其他条目。") }
        let old = entries
        entries.append(entry); entries.sort { $0.date > $1.date }
        prune()
        guard entries.contains(where: { $0.id == entry.id }), old.allSatisfy({ item in entries.contains(where: { $0.id == item.id }) }) else {
            entries = old; throw failure("此记录已过期或图片缓存容量不足，无法恢复。")
        }
        do { try persist() } catch { entries = old; throw error }
        deletedEntry = nil
        onChange?()
        return entry.id
    }
    func clear() throws {
        let old = entries
        entries = []
        do { try persist() } catch { entries = old; throw error }
        deletedEntry = nil
        error = nil
        notice = nil
        try removeUnusedImages()
        lastChange = pasteboard.changeCount
        start()
        onChange?()
    }
    private func prune() {
        let cutoff = now().addingTimeInterval(-Double(retentionDays) * 86400)
        var usedBytes = 0
        // Reserve count and image budget for pins before admitting ordinary history.
        let prioritized = entries.filter(\.isPinned) + entries.filter { !$0.isPinned }
        let retained = Array(prioritized.filter { entry in
            guard (entry.isPinned || entry.date > cutoff), entry.text.utf8.count <= Self.maximumTextBytes,
                  entry.paths.count <= 1000, entry.paths.joined().utf8.count <= Self.maximumTextBytes else { return false }
            if entry.kind == .image {
                guard let url = imageURL(for: entry), let attributes = try? FileManager.default.attributesOfItem(atPath: url.path),
                      let size = attributes[.size] as? NSNumber, size.intValue <= Self.maximumImageBytes else { return false }
                usedBytes += size.intValue
                return usedBytes <= Self.maximumCacheBytes
            }
            return true
        }.prefix(Self.maximumEntries))
        let ids = Set(retained.map(\.id))
        entries = entries.filter { ids.contains($0.id) }
    }
    private func persist() throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        let data = try JSONEncoder().encode(Document(enabled: enabled, retentionDays: retentionDays, entries: entries))
        try data.write(to: url, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
    private func removeUnusedImages() throws {
        let keep = Set(entries.compactMap(\.imageFile) + [deletedEntry?.imageFile].compactMap { $0 })
        guard let files = try? FileManager.default.contentsOfDirectory(at: imageDirectory, includingPropertiesForKeys: nil) else { return }
        for file in files where !keep.contains(file.lastPathComponent) {
            // Never remove arbitrary files outside the owned cache naming scheme.
            if file.lastPathComponent.range(of: "^[a-f0-9]{64}\\.(png|tiff)$", options: .regularExpression) != nil {
                try FileManager.default.removeItem(at: file)
            }
        }
    }
    private func saveOrPause() {
        do { try persist(); try removeUnusedImages() } catch { pauseAfterFailure(error) }
    }
    private func pauseAfterFailure(_ error: Error) {
        enabled = false
        self.error = "保存剪贴板历史失败，已暂停记录。\(error.localizedDescription)"
        stop()
        onChange?()
    }
    private func failure(_ message: String) -> Error {
        NSError(domain: "Clipboard", code: 1, userInfo: [NSLocalizedDescriptionKey: message])
    }
}
